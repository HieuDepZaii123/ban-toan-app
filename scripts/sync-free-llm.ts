/**
 * Regenerates server/chat/freeCatalog.ts from vendor/awesome-free-llm-apis/data.json.
 * Run with: npm run free-llm:sync        (write)
 *           tsx scripts/sync-free-llm.ts --check   (exit 1 if the file is stale)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { FREE_PROVIDERS } from "../server/chat/free.ts";

type RawModel = { id: string | null; rateLimit?: string };
type RawProvider = { name: string; url: string; baseUrl: string; description: string; models: RawModel[] };
type RawData = { lastUpdated: string; providers: RawProvider[] };

const root = fileURLToPath(new URL("..", import.meta.url));
const dataPath = `${root}vendor/awesome-free-llm-apis/data.json`;
const outPath = `${root}server/chat/freeCatalog.ts`;

export function renderCatalog(data: RawData): string {
  const wanted = new Set(FREE_PROVIDERS.map((provider) => provider.catalogName));
  const entries = data.providers
    .filter((provider) => wanted.has(provider.name))
    .map((provider) => ({
      name: provider.name,
      url: provider.url,
      baseUrl: provider.baseUrl,
      description: provider.description,
      models: provider.models
        .filter((model): model is RawModel & { id: string } => typeof model.id === "string" && model.id.length > 0)
        .map((model) => ({ id: model.id, rateLimit: model.rateLimit ?? "" })),
    }));
  return `// Generated by scripts/sync-free-llm.ts from vendor/awesome-free-llm-apis/data.json. Do not edit.
// Source: https://github.com/mnfst/awesome-free-llm-apis (CC0 1.0)

export type FreeCatalogEntry = {
  name: string;
  url: string;
  baseUrl: string;
  description: string;
  models: { id: string; rateLimit: string }[];
};

export const FREE_CATALOG_UPDATED = ${JSON.stringify(data.lastUpdated)};

export const FREE_CATALOG: FreeCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = renderCatalog(JSON.parse(readFileSync(dataPath, "utf8")) as RawData);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outPath, "utf8");
    } catch {
      // missing file counts as stale
    }
    if (current !== next) {
      console.error("server/chat/freeCatalog.ts is stale. Run: npm run free-llm:sync");
      process.exit(1);
    }
    console.log("free-llm catalog ok");
  } else {
    writeFileSync(outPath, next);
    console.log(`wrote ${outPath}`);
  }
}
