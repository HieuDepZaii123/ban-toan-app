def put(name, cond):
    if name in out:
        raise SystemExit("duplicate " + name)
    if isinstance(cond, sp.Basic):
        cond = sp.simplify(cond)
        if cond == True:
            cond = True
        elif cond == False:
            cond = False
        else:
            raise SystemExit(f"{name} did not decide: {cond}")
    if not isinstance(cond, bool):
        raise SystemExit(f"{name} not bool ({type(cond).__name__})")
    out[name] = cond

