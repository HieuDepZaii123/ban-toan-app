const R = String.raw;

function sinShow(value: number | undefined): string {
  const s = value ?? 0;
  if (Math.abs(s - 0.5) < 1e-9) return R`\dfrac{1}{2}`;
  if (Math.abs(s - Math.SQRT2 / 2) < 1e-9) return R`\dfrac{\sqrt{2}}{2}`;
  return R`\dfrac{\sqrt{3}}{2}`;
}

function cosOf(params: Params, sign: number): World {
  const s = params.s ?? 0;
  return { s, c: sign * Math.sqrt(1 - s * s) };
}

