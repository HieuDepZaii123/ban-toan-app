function signed(value: number | undefined): string {
  const n = value ?? 0;
  return n < 0 ? `(${n})` : String(n);
}

function paren(value: number | undefined): string {
  const n = value ?? 0;
  return n < 0 ? `(${n})` : String(n);
}

