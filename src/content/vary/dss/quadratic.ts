function positiveIntercept(params: Params): World {
  const r = params.r ?? 0;
  const s = params.s ?? 0;
  const a = r * s > 0 ? 1 : -1;
  return { r, s, a };
}

function negativeIntercept(params: Params): World {
  const r = params.r ?? 0;
  const s = params.s ?? 0;
  const a = r * s > 0 ? -1 : 1;
  return { r, s, a };
}

