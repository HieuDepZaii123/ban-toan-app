const R = String.raw;

/** b² − 4ac = Δ and c = 0, with b = ±√Δ. */
function onAxis(params: Params, sign: number): World {
  return { a: params.a ?? 0, b: sign * (params.root ?? 0), c: 0 };
}

/** Another point on the same a, Δ: b = √Δ + 2a, c = √Δ + a. */
function offAxis(params: Params): World {
  const a = params.a ?? 0;
  const root = params.root ?? 0;
  return { a, b: root + 2 * a, c: root + a };
}

