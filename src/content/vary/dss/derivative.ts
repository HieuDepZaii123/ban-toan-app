import { all, div, eq, gt, lt, mul, neg, never, num, par, sq, sub, wr, type Params, type World } from "./expr.ts";
import { fact, publishAll, varyAll, type DssItem } from "./item.ts";

const R = String.raw;

function flatWorld(params: Params, t: number): World {
  return { x0: params.x0 ?? 0, t };
}

