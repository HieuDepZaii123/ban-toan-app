/** Bản tiếng Anh của một hình: thay mọi chuỗi có trong bảng, giữ nguyên số liệu và màu. */
export function pictureInEnglish(spec: Picture): Picture {
  const swap = (value: unknown, key = ""): unknown => {
    if (typeof value === "string") return key === "k" || key === "tone" ? value : (pictureTextEn[value] ?? value);
    if (Array.isArray(value)) return value.map((item) => swap(item, key));
    if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, swap(v, k)]));
    return value;
  };
  return swap(spec) as Picture;
}
